"""Exercise the opt-in SQL against a disposable PostgreSQL schema.

TEST_DATABASE_URL=postgresql:///image2_auto_size_test python scripts/test_enable_image_auto.py
"""
import os
from pathlib import Path
import subprocess
import unittest
from urllib.parse import urlsplit
from uuid import uuid4

DATABASE = os.environ['TEST_DATABASE_URL']
assert 'test' in urlsplit(DATABASE).path.lower(), 'Requires a test database'
PSQL = os.environ.get('PSQL', 'psql')
SCRIPT = Path(__file__).with_name('enable-image-auto.sql').read_text()

FIXTURE = """
CREATE TABLE image_models (id bigint PRIMARY KEY, site_id bigint, name text, vendor_model text, is_active boolean);
CREATE TABLE image_resolution_specs (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, site_id bigint, code text, label text, sort_order integer, is_active boolean, UNIQUE(site_id,code));
CREATE TABLE image_aspect_ratio_specs (LIKE image_resolution_specs INCLUDING ALL);
CREATE TABLE image_model_resolutions (model_id bigint, resolution_id bigint, UNIQUE(model_id,resolution_id));
CREATE TABLE image_model_aspect_ratios (model_id bigint, aspect_ratio_id bigint, UNIQUE(model_id,aspect_ratio_id));
CREATE TABLE image_model_prices (id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, site_id bigint, model_id bigint, work_type text, resolution text, aspect_ratio text, output_count integer, credit_cost integer, version integer, is_active boolean, change_reason text, effective_at timestamptz DEFAULT now());
INSERT INTO image_models VALUES (1,1,'GPT test','gpt-image-2.5-sunburst',true),(2,2,'Other site','gpt-image-2',true);
INSERT INTO image_resolution_specs (site_id,code,label,is_active) VALUES (1,'1k','1K',true),(1,'4k','4K',true);
INSERT INTO image_aspect_ratio_specs (site_id,code,label,is_active) VALUES (1,'1:1','1:1',true),(1,'2:3','2:3',true);
INSERT INTO image_model_resolutions SELECT 1,id FROM image_resolution_specs;
INSERT INTO image_model_aspect_ratios SELECT 1,id FROM image_aspect_ratio_specs;
INSERT INTO image_model_prices (site_id,model_id,work_type,resolution,aspect_ratio,output_count,credit_cost,version,is_active,change_reason)
SELECT 1,1,w,r,a,1,CASE r WHEN '1k' THEN 7 ELSE 12 END,1,true,'fixture'
FROM unnest(ARRAY['text_to_image','image_to_image']) w,
     unnest(ARRAY['1k','4k']) r, unnest(ARRAY['1:1','2:3']) a;
"""

class AutoSizeConfigTests(unittest.TestCase):
    def execute(self, sql, *, apply=True, models='1', check=True):
        result = subprocess.run([PSQL,DATABASE,'-X','-At','-v','ON_ERROR_STOP=1',
            '-v','site_id=1','-v',f'model_ids={models}','-v','baseline_resolution=1k',
            '-v',f'apply={str(apply).lower()}'],
            input=f'SET search_path TO {self.schema};\n'+sql,text=True,capture_output=True)
        if check: self.assertEqual(result.returncode,0,result.stderr)
        return result

    def setUp(self):
        self.schema='auto_size_test_'+uuid4().hex
        self.execute(f'CREATE SCHEMA {self.schema}; SET search_path TO {self.schema};'+FIXTURE)

    def tearDown(self):
        self.execute(f'DROP SCHEMA {self.schema} CASCADE;')

    def scalar(self, sql):
        return self.execute(sql).stdout.strip().splitlines()[-1]

    def test_dry_run_apply_prices_idempotence_and_existing_price_preservation(self):
        self.execute(SCRIPT,apply=False)
        self.assertEqual(self.scalar('SELECT count(*) FROM image_model_prices'), '8')
        self.assertEqual(self.scalar("SELECT count(*) FROM image_resolution_specs WHERE code='auto'"), '0')
        self.execute(SCRIPT)
        self.assertEqual(self.scalar('SELECT count(*) FROM image_model_prices'), '18')
        self.assertEqual(self.scalar("SELECT credit_cost FROM image_model_prices WHERE work_type='text_to_image' AND resolution='auto' AND aspect_ratio='auto'"), '7')
        self.assertEqual(self.scalar("SELECT credit_cost FROM image_model_prices WHERE work_type='text_to_image' AND resolution='4k' AND aspect_ratio='auto'"), '12')
        self.assertEqual(self.scalar('SELECT count(*) FROM image_model_resolutions WHERE model_id=2'), '0')
        self.execute("UPDATE image_model_prices SET credit_cost=9 WHERE resolution='auto' AND aspect_ratio='auto'")
        self.execute(SCRIPT)
        self.assertEqual(self.scalar('SELECT count(*) FROM image_model_prices'), '18')
        self.assertEqual(self.scalar("SELECT min(credit_cost) FROM image_model_prices WHERE resolution='auto' AND aspect_ratio='auto'"),'9')

    def test_cross_site_selection_is_rejected_without_writes(self):
        result=self.execute(SCRIPT,models='1,2',check=False)
        self.assertNotEqual(result.returncode,0)
        self.assertIn('selected site',result.stderr)
        self.assertEqual(self.scalar('SELECT count(*) FROM image_model_prices'),'8')

    def test_ambiguous_ratio_pricing_is_rejected_atomically(self):
        self.execute("UPDATE image_model_prices SET credit_cost=20 WHERE aspect_ratio='2:3'")
        result=self.execute(SCRIPT,check=False)
        self.assertNotEqual(result.returncode,0)
        self.assertIn('explicit Auto pricing',result.stderr)
        self.assertEqual(self.scalar("SELECT count(*) FROM image_resolution_specs WHERE code='auto'"),'0')

    def test_latest_active_prices_are_copied(self):
        self.execute("UPDATE image_model_prices SET effective_at=now()-interval '1 day'; INSERT INTO image_model_prices(site_id,model_id,work_type,resolution,aspect_ratio,output_count,credit_cost,version,is_active,change_reason) SELECT site_id,model_id,work_type,resolution,aspect_ratio,output_count,9,2,true,'new price' FROM image_model_prices WHERE resolution='1k'")
        self.execute(SCRIPT)
        self.assertEqual(self.scalar("SELECT min(credit_cost) FROM image_model_prices WHERE resolution='auto'"),'9')

if __name__ == '__main__':
    unittest.main()
